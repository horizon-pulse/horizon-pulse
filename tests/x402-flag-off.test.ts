describe("flag off: byte-identical to origin/main", () => {
  beforeEach(() => {
    installFacilitatorMock();
    vi.spyOn(console, "warn").mockImplementation(() => {});
  });
  afterEach(() => {
    vi.unstubAllEnvs();
    vi.restoreAllMocks();
  });

  if (process.env.UPDATE_GOLDEN === "1") {
    it("writes the golden fixture (run on origin/main only)", async () => {
      const all = await captureWith({});
      writeFileSync(GOLDEN, JSON.stringify(all, null, 1) + "\n");
    });
    return;
  }

  it("golden fixture exists", () => {
    expect(existsSync(GOLDEN)).toBe(true);
  });

  for (const [name, env] of Object.entries(OFF_VARIANTS)) {
    it(`env ${name}`, async () => {
      const golden = readFileSync(GOLDEN, "utf8");
      const all = await captureWith(env);
      // Whole-object string compare = byte-identical bodies + headers + status.
      expect(JSON.stringify(all, null, 1) + "\n").toBe(golden);
    });
  }
});
